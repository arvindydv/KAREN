/**
 * Versioned deterministic lexicons for the memory write policy (arch §7.3 V6, V7, V10).
 *
 * Patterns are phrases of space-separated words. Each word is folded with the same function as
 * search tokens (`foldToken`), so Latin case/vowel/plural variants and Devanagari nukta variants
 * match. A word ending in `*` is a prefix match on the folded token. `#` matches any number token.
 *
 * Any change to any list is a policy change: bump MEMORY_POLICY_VERSION (recorded on every
 * extraction job, `extraction_jobs.policy_version`, L-08). Category lists are PENDING LEGAL REVIEW
 * (LEG-3); they reject, never store.
 */
import { foldToken, type OffsetToken } from './normalise.js';

export const MEMORY_POLICY_VERSION = 'mp-1';

interface CompiledWord {
  readonly value: string;
  readonly prefix: boolean;
  readonly number: boolean;
}
export type CompiledPhrase = readonly CompiledWord[];

export function compilePhrase(pattern: string): CompiledPhrase {
  return pattern
    .trim()
    .split(/\s+/u)
    .map((w) => {
      if (w === '#') return { value: '', prefix: false, number: true };
      const prefix = w.endsWith('*');
      const raw = prefix ? w.slice(0, -1) : w;
      // Fold without the plural rule for prefixes (a prefix is not a word).
      const value = prefix ? raw.toLowerCase().replace(/़/gu, '') : foldToken(raw);
      return { value, prefix, number: false };
    });
}

function wordMatches(word: CompiledWord, tok: string): boolean {
  if (word.number) return /^\p{N}+$/u.test(tok);
  return word.prefix ? tok.startsWith(word.value) : tok === word.value;
}

export interface PhraseHit {
  /** Index of the first matched token. */
  readonly from: number;
  /** Index one past the last matched token. */
  readonly to: number;
}

/** All occurrences of any phrase in a folded token list (contiguous match). */
export function findPhrases(
  tokens: readonly string[],
  phrases: readonly CompiledPhrase[],
): PhraseHit[] {
  const hits: PhraseHit[] = [];
  for (const phrase of phrases) {
    for (let i = 0; i + phrase.length <= tokens.length; i++) {
      let ok = true;
      for (let k = 0; k < phrase.length; k++) {
        if (!wordMatches(phrase[k]!, tokens[i + k]!)) {
          ok = false;
          break;
        }
      }
      if (ok) hits.push({ from: i, to: i + phrase.length });
    }
  }
  return hits.sort((a, b) => a.from - b.from || b.to - a.to);
}

export const tokensOf = (t: readonly OffsetToken[]): string[] => t.map((x) => x.tok);

const compileAll = (list: readonly string[]): CompiledPhrase[] => list.map(compilePhrase);

